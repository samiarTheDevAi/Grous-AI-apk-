# v1 JAR signature — file digests (hard) + section digests (report)
# --------------------------------------------------------------------------

def _jar_name(name):
    """JAR spec 75-char Name truncation."""
    return name if len(name) <= JAR_NAME_LIMIT else name[:JAR_NAME_LIMIT]


def _digest_value(line, label):
    if line.startswith(label + ': '):
        try:
            return base64.b64decode(line[len(label) + 2:].strip()).hex()
        except Exception:
            return None
    return None


def verify_v1_signature(zf):
    names = zf.namelist()
    if 'META-INF/MANIFEST.MF' not in names:
        return {'present': False}
    sf_names = [n for n in names
                if n.startswith('META-INF/') and n.endswith('.SF')]
    rsa_names = [n for n in names
                 if n.startswith('META-INF/') and
                 (n.endswith('.RSA') or n.endswith('.DSA') or n.endswith('.EC'))]
    out = {
        'present': True,
        'sf_files': sf_names,
        'signing_files': rsa_names,
        'manifest_entries': 0,
        'file_digests_verified': 0,
        'file_digest_mismatches': [],
        'uncovered_entries': [],
        'section_digests_checked': 0,
        'section_digest_mismatches': 0,
        'complete': bool(sf_names and rsa_names),
    }
    mf_text = zf.read('META-INF/MANIFEST.MF').decode('latin-1', 'replace')
    mf_lines = mf_text.splitlines()

    # map: jar-name -> sha256 hex
    manifest_digests = {}
    cur = None
    for line in mf_lines:
        if line.startswith('Name: '):
            cur = _jar_name(line[6:].strip())
            manifest_digests[cur] = None
        elif cur:
            d = _digest_value(line, 'SHA-256-Digest') or \
                _digest_value(line, 'SHA-256')
            if d:
                manifest_digests[cur] = d
    out['manifest_entries'] = len(manifest_digests)

    sig_files = {'META-INF/MANIFEST.MF'} | set(sf_names) | set(rsa_names)
    name_set = set(names)
    # (a) file digests vs actual bytes (truncation-aware)
    checked = 0
    for entry, dig in manifest_digests.items():
        if dig is None:
            continue
        norm = entry.lstrip('/')
        # find the real APK entry (may be longer than the truncated name)
        real = norm if norm in name_set else None
        if real is None:
            for n in name_set:
                if _jar_name(n) == entry:
                    real = n
                    break
        if real is None or real in sig_files:
            continue
        actual = hashlib.sha256(zf.read(real)).hexdigest()
        checked += 1
        if actual != dig:
            out['file_digest_mismatches'].append(real)
    out['file_digests_verified'] = checked
    covered = set(manifest_digests)
    for n in names:
        if n in sig_files or n.endswith('/'):
            continue
        if n not in covered and _jar_name(n) not in covered:
            out['uncovered_entries'].append(n)

    # (b) MANIFEST.MF section digests vs *.SF (informational)
    sections = {}
    cur = None
    for line in mf_lines:
        if line.startswith('Name: '):
            cur = line[6:].strip()
            sections[cur] = [line]
        elif line == '':
            cur = None
        elif cur is not None:
            sections[cur].append(line)
    for sf in sf_names:
        sf_text = zf.read(sf).decode('latin-1', 'replace')
        sf_lines = sf_text.splitlines()
        sf_pos = {}
        for i, ln in enumerate(sf_lines):
            if ln.startswith('Name: '):
                sf_pos[_jar_name(ln[6:].strip())] = i
        for entry, lines in sections.items():
            if entry not in sf_pos:
                continue
            norm = b''.join(l.rstrip('\r\n').encode('latin-1', 'replace')
                            + b'\n' for l in lines)
            expected = hashlib.sha256(norm).hexdigest()
            i = sf_pos[entry]
            got = None
            for j in range(i + 1, len(sf_lines)):
                d = _digest_value(sf_lines[j], 'SHA-256-Digest') or \
                    _digest_value(sf_lines[j], 'SHA-256')
                if d:
                    got = d
                    break
                if sf_lines[j].startswith('Name: ') or sf_lines[j] == '':
                    break
            if got is None:
                continue
            out['section_digests_checked'] += 1
            if got != expected:
                out['section_digest_mismatches'] += 1
    return out


