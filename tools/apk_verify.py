# APK Signing Block — located via EOCD, certificate extracted by DER scan
# --------------------------------------------------------------------------

def find_signing_block(raw):
    """Return (start, end, {scheme_id: value_bytes}) or None if v1-only.

    Tolerates trailing all-zero padding inside the block (some third-party
    signing tools, e.g. Signflinger, zero-fill the block without writing
    exact id-value entries all the way to the trailer). Non-zero stray bytes
    are still treated as corruption.
    """
    eocd = raw.rfind(b'PK\x05\x06')
    if eocd < 0:
        raise Failure('ZIP End-Of-Central-Directory record not found')
    cd_off = _u32(raw, eocd + 16)
    if cd_off < 32 or cd_off + 16 > len(raw):
        return None
    if raw[cd_off - 16:cd_off] != SIGNING_MAGIC:
        return None  # no APK Signing Block (v1-only APK)
    size = struct.unpack_from('<Q', raw, cd_off - 24)[0]
    if size < 32 or size > cd_off:
        raise Failure('corrupt signing block size field')
    start = cd_off - size
    end = cd_off
    entries = {}
    o = start + 8  # skip the leading size field
    trailer = end - 24  # second size field + magic
    while o + 8 <= trailer:
        chunk_id = _u32(raw, o)
        val_len = _u32(raw, o + 4)
        if o + 8 + val_len > trailer:
            raise Failure('corrupt signing block entry')
        if chunk_id or val_len:
            entries[chunk_id] = raw[o + 8:o + 8 + val_len]
        o += 8 + val_len
    if o != trailer:
        if any(raw[o:trailer]):
            raise Failure('corrupt signing block (unparsed trailing bytes)')
        # all-zero padding — tolerated
    return start, end, entries


def _der_len(data, o):
    ln = data[o]
    o += 1
    if ln & 0x80:
        n = ln & 0x7F
        ln = int.from_bytes(data[o:o + n], 'big')
        o += n
    return ln, o


def _der_items(data, o, end):
    """Yield (tag, value_bytes) for DER items in data[o:end]."""
    while o < end:
        tag = data[o]
        ln, o2 = _der_len(data, o + 1)
        yield tag, data[o2:o2 + ln]
        o = o2 + ln


def extract_cert(data):
    """Find the first X.509 certificate (DER) inside a byte blob.

    Layout-agnostic: scans for a long-form SEQUENCE whose contents look like
    an RSA certificate (RSA OID present, plausible length). Works for both
    standard apksigner v2 blocks and third-party (e.g. Signflinger) layouts.
    """
    i = 0
    n = len(data)
    while i < n - 4:
        if data[i] == 0x30 and data[i + 1] == 0x82:
            ln = (data[i + 2] << 8) | data[i + 3]
            end = i + 4 + ln
            if end <= n and 200 < ln < 20000 and RSA_OID in data[i:end]:
                return data[i:end]
            i += 4
        else:
            i += 1
    return None


def parse_cert_subject(cert):
    """Return a rough subject string (e.g. 'Android Debug') from a DER cert."""
    try:
        # Certificate ::= SEQ { tbs SEQ {...} , sigAlg, sig }
        outer = list(_der_items(cert, 0, len(cert)))
        tbs = outer[0][1]
        cn_oid = bytes.fromhex('0603550403')  # 2.5.4.3
        idx = tbs.find(cn_oid)
        if idx >= 0:
            seg = tbs[idx + len(cn_oid):idx + len(cn_oid) + 128]
            for tag, val in _der_items(seg, 0, len(seg)):
                if tag in (0x0C, 0x13, 0x16):  # UTF8 / Printable / IA5
                    return val.decode('utf-8', 'replace')
        # fallback: last human-readable string in the TBS
        strings = []

        def walk(b):
            for tag, val in _der_items(b, 0, len(b)):
                if tag in (0x0C, 0x13, 0x16):
                    strings.append(val.decode('utf-8', 'replace'))
                elif tag == 0x30:
                    walk(val)

        walk(tbs)
        return strings[-1] if strings else ''
    except Exception:
        return ''


def parse_cert_key_bits(cert):
    """Return the RSA public-key size in bits, or None."""
    try:
        cert_items = list(_der_items(cert, 0, len(cert)))
        if not cert_items or cert_items[0][0] != 0x30:
            return None
        # Certificate ::= SEQ { TBSCertificate, sigAlg, sigValue }
        contents = list(_der_items(cert_items[0][1], 0,
                                   len(cert_items[0][1])))
        if not contents or contents[0][0] != 0x30:
            return None
        tbscert = contents[0][1]  # TBSCertificate
        # SubjectPublicKeyInfo = SEQ { algId SEQ, BIT STRING }; it is the
        # last field of TBSCertificate. Identify it structurally so we don't
        # confuse it with Name (SEQ of SETs) or Validity (SEQ of times).
        for tag, val in _der_items(tbscert, 0, len(tbscert)):
            if tag != 0x30:
                continue
            sub = list(_der_items(val, 0, len(val)))
            if len(sub) == 2 and sub[0][0] == 0x30 and sub[1][0] == 0x03 \
                    and len(sub[1][1]) > 64:
                bitstring = sub[1][1]
                if not bitstring or bitstring[0] != 0:
                    continue
                key_items = list(_der_items(bitstring[1:], 0,
                                            len(bitstring) - 1))
                if not key_items or key_items[0][0] != 0x30:
                    continue
                keyseq = key_items[0][1]
                nums = [int.from_bytes(v, 'big')
                        for tt, v in _der_items(keyseq, 0, len(keyseq))
                        if tt == 0x02]
                if nums:
                    return nums[0].bit_length()
        return None
    except Exception:
        return None


def analyze_signing(raw):
    """Return a dict describing the signatures present in the APK."""
    res = find_signing_block(raw)
    out = {
        'schemes': [],
        'cert': None,
        'cert_subject': None,
        'cert_key_bits': None,
        'cert_sha256': None,
    }
    if res is None:
        return out
    _, _, entries = res
    out['schemes'] = [SCHEME_IDS.get(k, '0x%08x' % k) for k in entries]
    # prefer v2, then v3, then v3.1 for certificate extraction
    for scheme in ('v2', 'v3', 'v3.1'):
        if scheme in out['schemes']:
            sid = [k for k, v in SCHEME_IDS.items()
                   if v == scheme][0]
            cert = extract_cert(entries[sid])
            if cert:
                out['cert'] = cert
                out['cert_subject'] = parse_cert_subject(cert)
                out['cert_key_bits'] = parse_cert_key_bits(cert)
                out['cert_sha256'] = hashlib.sha256(cert).hexdigest()
                break
    return out


