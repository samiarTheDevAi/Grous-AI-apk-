#!/usr/bin/env python3
"""Verify a Grous AI release APK — no Android SDK or Java required.

What this tool checks (pure Python, stdlib only):

  1. ZIP integrity        every entry decompresses with a valid CRC-32.
  2. Manifest audit       decodes the binary AndroidManifest.xml with a
                          built-in AXML parser and reports package, version,
                          min/target SDK, permissions, activities, debuggable.
  3. Permission baseline  FAILS if the APK requests any permission outside
                          PERMISSION_BASELINE (INTERNET + the app's own
                          signature-level permission).
  4. Release sanity       FAILS if the package name is wrong.  Being built
                          debuggable is a WARNING by default (promoted to a
                          hard failure with --strict), as is a debug-keystore
                          signing certificate.
  5. Signature detection  locates the APK Signing Block (v2/v3) via the ZIP
                          End-Of-Central-Directory record and reports which
                          schemes are present.
  6. Signing certificate  extracts the signer certificate from the v2/v3
                          block (layout-agnostic DER scan) and reports its
                          subject, key size and SHA-256 fingerprint.
                          WARNs when the key looks like the Android debug
                          keystore — a debug-signed APK is not a release key.
  7. v1 JAR integrity     verifies every file digest recorded in
                          META-INF/MANIFEST.MF against the actual APK bytes
                          (handles the JAR spec's 75-char Name truncation and
                          SHA-256-Digest labels). A mismatch = tampering and
                          FAILS the build. Also cross-checks the CERT.SF
                          section digests against MANIFEST.MF and REPORTS any
                          inconsistency (a common artifact of third-party
                          re-signing tools; on Android 7.0+ the v2 block is
                          the authoritative signature, so this is a warning,
                          not a hard failure).
  8. SHA-256              prints the artifact hash for pinning.

Hard failures (always): not-a-zip / corrupt zip, wrong package name,
unexpected permissions, no signature at all, v1 file-digest mismatch
(tampering).

Warnings (pass by default): signed with the Android debug keystore, built
debuggable, v1-only signature (no v2/v3 block), v1 CERT.SF<->MANIFEST
inconsistency, uncovered entries.  Run with --strict to promote the
debug-keystore and debuggable warnings to hard failures (the correct gate
for a production release).

Exit code 0 = pass (warnings allowed), 1 = fail, 2 = usage/IO error.

Usage:
    python3 apk_verify.py <path-to-apk> [--report-dir DIR] [--json] [--strict]
"""
import base64
import hashlib
import json
import os
import struct
import sys
import zipfile

# Permissions a Grous AI release APK is allowed to request.
# Anything else fails the audit — add a new entry only with an explicit
# decision recorded in the PR/commit message.
PERMISSION_BASELINE = {
    'android.permission.INTERNET',
    # auto-generated by AGP for ContextCompat.registerReceiver(...,
    # RECEIVER_NOT_EXPORTED); signature-protected, internal to the package
    'com.grous.ai.DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION',
}

EXPECTED_PACKAGE = 'com.grous.ai'

# APK Signing Block magic: "APK Sig Block 42" (16 bytes)
SIGNING_MAGIC = b'APK Sig Block 42'
SCHEME_IDS = {
    0x7109871a: 'v2',
    0xf05368c0: 'v3',
    0x1b93ad61: 'v3.1',
}

# JAR spec: "Name:" lines must not exceed 75 characters; long entry names
# are truncated to 75 chars in the signature files.
JAR_NAME_LIMIT = 75

# RSA OID 1.2.840.113549.1.1 — used to recognise X.509 cert / SPKI blobs.
RSA_OID = b'\x06\x09\x2a\x86\x48\x86\xf7\x0d\x01\x01\x01'


class Failure(Exception):
    pass


def _u16(b, o):
    return struct.unpack_from('<H', b, o)[0]


def _i32(b, o):
    return struct.unpack_from('<i', b, o)[0]


def _u32(b, o):
    return struct.unpack_from('<I', b, o)[0]


# --------------------------------------------------------------------------
# AXML (binary XML) parser — string pool + element/attribute walk
# --------------------------------------------------------------------------

class Axml:
    def __init__(self, data):
        self.data = data
        if len(data) < 16 or _u16(data, 0) != 0x0003:
            raise ValueError('not an AXML file')
        off = 8
        if _u16(data, off) != 0x0001:
            raise ValueError('no string pool')
        self.sp_size = _u32(data, off + 4)
        self.n_strings = _u32(data, off + 8)
        self.is_utf8 = bool(_u32(data, off + 16) & (1 << 8))
        self.str_start = _u32(data, off + 20)
        self.str_offs = [_u32(data, off + 28 + i * 4)
                         for i in range(self.n_strings)]
        self.base = off + self.str_start
        self.strings = [self._read_string(i) for i in range(self.n_strings)]
        # resource-id map (0x0180 chunk)
        o = off + self.sp_size
        self.res_ids = []
        while o < len(data):
            t = _u16(data, o)
            csize = _u32(data, o + 4)
            if t == 0x0180:
                n = (csize - 8) // 4
                self.res_ids = [_u32(data, o + 8 + i * 4) for i in range(n)]
                break
            o += csize

    def _varint(self, p):
        x = self.data[p]
        if x & 0x80:
            return ((x & 0x7F) << 8) | self.data[p + 1], p + 2
        return x, p + 1

    def _read_string(self, idx):
        if idx is None or idx < 0 or idx >= self.n_strings:
            return ''
        p = self.base + self.str_offs[idx]
        if self.is_utf8:
            _, p = self._varint(p)
            blen, p = self._varint(p)
            return self.data[p:p + blen].decode('utf-8', 'replace')
        n = _u16(self.data, p)
        p += 2
        return self.data[p:p + n * 2].decode('utf-16-le', 'replace')

    def s(self, idx):
        if idx is None or idx < 0 or idx >= self.n_strings:
            return ''
        return self.strings[idx]

    def walk(self):
        """Yield (tag, {attr: value}) for start tags, in document order."""
        o = 8 + self.sp_size
        while o < len(self.data):
            t = _u16(self.data, o)
            hsize = _u16(self.data, o + 2)
            csize = _u32(self.data, o + 4)
            if t == 0x0102:  # RES_XML_START_ELEMENT
                ext = o + hsize
                name = self.s(_i32(self.data, ext + 4))
                a_start = _u16(self.data, ext + 8)
                a_size = _u16(self.data, ext + 10)
                n_a = _u16(self.data, ext + 12)
                attrs = {}
                for i in range(n_a):
                    a = ext + a_start + i * a_size
                    raw = _i32(self.data, a + 8)
                    # Res_value: size(u16 @a+12) res0(u8 @a+14)
                    #           dataType(u8 @a+15) data(u32 @a+16)
                    ty = self.data[a + 15]
                    dv = _u32(self.data, a + 16)
                    if ty == 0x03:          # RES_VALUE_TYPE_STRING
                        val = self.s(dv) if raw < 0 else self.s(raw)
                    elif ty == 0x10:        # RES_VALUE_TYPE_INT_DEC
                        val = dv
                    elif ty == 0x11:        # RES_VALUE_TYPE_INT_HEX
                        val = '0x%x' % dv
                    elif ty == 0x12:        # RES_VALUE_TYPE_INT_BOOLEAN
                        val = bool(dv)
                    elif ty in (0x01, 0x1f):  # RES_VALUE_TYPE_REFERENCE
                        val = '@0x%08x' % dv
                    else:
                        val = self.s(raw) if raw >= 0 else str(dv)
                    # Attribute names are always present in the string pool;
                    # the resource-id map is only a secondary hint and can be
                    # misaligned, so prefer the string name.
                    an = self.s(_i32(self.data, a + 4))
                    if not an and i < len(self.res_ids) and self.res_ids[i]:
                        an = _RES_ID_NAMES.get(self.res_ids[i], '')
                    attrs[an] = val
                yield name, attrs
            o += csize


