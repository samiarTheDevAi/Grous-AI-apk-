def verify(apk_path, report_dir=None, strict=False):
    # issues that are warnings by default but hard failures under --strict
    strict_issues = []
    report = {
        'apk': os.path.basename(apk_path),
        'sha256': None,
        'zip_entries': 0,
        'signing': None,
        'v1': None,
        'manifest': None,
        'unexpected_permissions': [],
        'debuggable': None,
        'warnings': [],
        'errors': [],
        'passed': False,
    }
    warnings = report['warnings']

    # 1. ZIP integrity
    if not zipfile.is_zipfile(apk_path):
        raise Failure('not a valid ZIP/APK file')
    with zipfile.ZipFile(apk_path) as zf:
        bad = zf.testzip()
        if bad is not None:
            raise Failure(f'corrupt ZIP entry: {bad}')
        report['zip_entries'] = len(zf.namelist())
        # 7. v1 digest checks
        report['v1'] = verify_v1_signature(zf)
    with open(apk_path, 'rb') as f:
        raw = f.read()

    # 5. + 6. signature detection & certificate
    report['signing'] = analyze_signing(raw)
    sig = report['signing']

    # 2. + 3. + 4. manifest audit
    man, _ = decode_manifest(apk_path)
    report['manifest'] = man
    report['debuggable'] = man['debuggable']
    if man['package'] != EXPECTED_PACKAGE:
        raise Failure(f"package is {man['package']!r}, expected "
                      f"{EXPECTED_PACKAGE!r}")
    extra = [p for p in man['permissions'] if p not in PERMISSION_BASELINE]
    report['unexpected_permissions'] = extra
    if extra:
        raise Failure(f'unexpected permissions requested: {extra}')
    if man['debuggable'] not in (False, 0, None):
        strict_issues.append('built debuggable (android:debuggable="true") — '
                             'a debuggable build lets anyone attach a '
                             'debugger; rebuild with a release buildType')
    if man['usesCleartextTraffic']:
        warnings.append('usesCleartextTraffic="true" — cleartext (non-HTTPS) '
                        'traffic is permitted; keep this only if the app '
                        'intentionally calls plain-HTTP endpoints')
    if man['versionName'] is None or man['versionCode'] is None:
        warnings.append('versionCode/versionName missing from manifest')

    # signature verdict
    has_v2v3 = any(s in ('v2', 'v3', 'v3.1') for s in sig['schemes'])
    v1 = report['v1']
    if not has_v2v3 and not v1['present']:
        raise Failure('APK carries no signature (no v2/v3 block, no v1 files)')
    if not has_v2v3 and v1['present']:
        warnings.append('v1-only signature: installs via sideload, but a '
                        'release build should add a v2/v3 APK Signing Block '
                        '(required by the Play Store and by Android 7.0+ '
                        'verification)')

    # certificate findings
    subj = (sig['cert_subject'] or '')
    if sig['cert_sha256'] and 'debug' in subj.lower():
        msg = (f'signed with the Android DEBUG keystore (subject: {subj!r}) '
               f'— re-sign with a proper release key before wide '
               f'distribution; a debug key is machine-specific and cannot '
               f'sign future updates under a different key')
        strict_issues.append(msg)
        warnings.append(msg)
    if has_v2v3 and not sig['cert_sha256']:
        warnings.append('v2/v3 block present but no signer certificate '
                        'could be extracted')

    # v1 integrity findings
    if v1['present']:
        if v1['file_digest_mismatches']:
            raise Failure('v1 MANIFEST.MF file digests do not match the '
                          f'APK contents (tampering?): '
                          f"{v1['file_digest_mismatches'][:5]}")
        if v1['uncovered_entries']:
            warnings.append(f'{len(v1["uncovered_entries"])} APK entries are '
                            f'not covered by MANIFEST.MF')
        if v1['section_digests_checked']:
            mm = v1['section_digest_mismatches']
            if mm:
                warnings.append(
                    f'CERT.SF section digests disagree with MANIFEST.MF '
                    f'for {mm}/{v1["section_digests_checked"]} sections — '
                    f'a typical artifact of third-party re-signing; on '
                    f'Android 7.0+ the v2 block is authoritative, but '
                    f're-signing a release APK with an external tool is '
                    f'not recommended')
            if not v1['complete']:
                warnings.append('v1 signature files incomplete '
                                '(missing *.SF or *.RSA)')

    report['strict_issues'] = strict_issues
    if strict and strict_issues:
        raise Failure('strict mode — ' + ' | '.join(strict_issues))

    report['sha256'] = hashlib.sha256(raw).hexdigest()
    report['passed'] = True

    if report_dir:
        _write_report(report, report_dir)
    return report


def _write_report(report, report_dir):
    os.makedirs(report_dir, exist_ok=True)
    with open(os.path.join(report_dir, 'verify-report.json'), 'w') as f:
        json.dump(report, f, indent=2, default=str)
    with open(os.path.join(report_dir, 'sha256.txt'), 'w') as f:
        f.write(f"{report['sha256']}  {report['apk']}\n")
    m = report['manifest']
    sig = report['signing']
    v1 = report['v1']
    lines = [
        f"package:                 {m['package']}",
        f"version:                 {m['versionCode']} ({m['versionName']})",
        f"minSdkVersion:           {m['minSdkVersion']}",
        f"targetSdkVersion:        {m['targetSdkVersion']}",
        f"platformBuildVersion:    {m['platformBuildVersionCode']} "
        f"({m['platformBuildVersionName']})",
        f"debuggable:              {m['debuggable']}",
        f"allowBackup:             {m['allowBackup']}",
        f"usesCleartextTraffic:    {m['usesCleartextTraffic']}",
        f"zip entries:             {report['zip_entries']}",
        f"signing schemes:         "
        f"{', '.join(sig['schemes']) or 'none (v1-only)'}",
    ]
    if sig['cert_sha256']:
        lines.append(f"signing certificate:     {sig['cert_subject'] or 'n/a'}"
                     f" (RSA-{sig['cert_key_bits']})")
        lines.append(f"cert SHA-256:            {sig['cert_sha256']}")
    if v1['present']:
        lines.append(f"v1 manifest entries:     {v1['manifest_entries']}")
        lines.append(f"v1 file digests verified: {v1['file_digests_verified']}")
        lines.append(f"v1 section digests:      "
                     f"{v1['section_digests_checked'] - v1['section_digest_mismatches']}"
                     f"/{v1['section_digests_checked']} consistent")
    lines.append('permissions:')
    for p in m['permissions']:
        mark = 'ok ' if p in PERMISSION_BASELINE else '!!!'
        lines.append(f"  [{mark}] {p}")
    lines.append('activities:')
    for a in m['activities']:
        lines.append(f"  {a['name']} exported={a['exported']}")
    lines.append(f"SHA-256: {report['sha256']}")
    if report['warnings']:
        lines.append('warnings:')
        for w in report['warnings']:
            lines.append(f"  ! {w}")
    strict = report.get('strict_issues', [])
    unseen = [s for s in strict if s not in report['warnings']]
    if unseen:
        lines.append('strict-only issues (fail with --strict):')
        for s in unseen:
            lines.append(f"  # {s}")
    with open(os.path.join(report_dir, 'manifest-summary.txt'), 'w') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    args = list(sys.argv[1:])
    report_dir = None
    as_json = '--json' in args
    strict = '--strict' in args
    for flag in ('--json', '--strict'):
        if flag in args:
            args.remove(flag)
    if '--report-dir' in args:
        i = args.index('--report-dir')
        report_dir = args[i + 1]
        del args[i:i + 2]
    if len(args) != 1:
        print(__doc__)
        return 2
    apk = args[0]
    if not os.path.isfile(apk):
        print(f'error: file not found: {apk}', file=sys.stderr)
        return 2
    try:
        report = verify(apk, report_dir, strict=strict)
    except Failure as e:
        print(f'FAIL  {e}', file=sys.stderr)
        print(f'      {apk}', file=sys.stderr)
        return 1
    m = report['manifest']
    sig = report['signing']
    print(f"PASS  {report['apk']}")
    print(f"      package    : {m['package']}")
    print(f"      version    : {m['versionCode']} ({m['versionName']})")
    print(f"      minSdk     : {m['minSdkVersion']}   targetSdk: "
          f"{m['targetSdkVersion']}")
    print(f"      permissions: {', '.join(m['permissions'])}")
    print(f"      signing    : {', '.join(sig['schemes']) or 'v1-only'}"
          + (f"  (cert: {sig['cert_subject']})" if sig['cert_subject'] else ''))
    print(f"      SHA-256    : {report['sha256']}")
    for w in report['warnings']:
        print(f"      warning  : {w}")
    for s in report.get('strict_issues', []):
        if s not in report['warnings']:
            print(f"      strict   : {s}  (use --strict to fail on this)")
    if as_json:
        print(json.dumps(report, indent=2, default=str))
    return 0


if __name__ == '__main__':
    sys.exit(main())
