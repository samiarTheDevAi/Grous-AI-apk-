def decode_manifest(apk):
    """Return a structured view of the manifest."""
    with zipfile.ZipFile(apk) as z:
        data = z.read('AndroidManifest.xml')
    ax = Axml(data)
    out = {
        'package': None, 'versionCode': None, 'versionName': None,
        'minSdkVersion': None, 'targetSdkVersion': None,
        'platformBuildVersionCode': None, 'platformBuildVersionName': None,
        'debuggable': None, 'allowBackup': None,
        'usesCleartextTraffic': None, 'permissions': [],
        'declared_permissions': [], 'activities': [],
        'providers': [],
    }
    for tag, attrs in ax.walk():
        if tag == 'manifest':
            out['package'] = attrs.get('package')
            out['versionCode'] = attrs.get('versionCode')
            out['versionName'] = attrs.get('versionName')
            out['platformBuildVersionCode'] = attrs.get(
                'platformBuildVersionCode')
            out['platformBuildVersionName'] = attrs.get(
                'platformBuildVersionName')
        elif tag == 'uses-sdk':
            out['minSdkVersion'] = attrs.get('minSdkVersion')
            out['targetSdkVersion'] = attrs.get('targetSdkVersion')
        elif tag == 'uses-permission':
            out['permissions'].append(attrs.get('name'))
        elif tag == 'permission':
            out['declared_permissions'].append(
                {'name': attrs.get('name'),
                 'protectionLevel': attrs.get('protectionLevel')})
        elif tag == 'application':
            out['debuggable'] = attrs.get('debuggable')
            out['allowBackup'] = attrs.get('allowBackup')
            out['usesCleartextTraffic'] = attrs.get('usesCleartextTraffic')
        elif tag == 'activity':
            out['activities'].append(
                {'name': attrs.get('name'),
                 'exported': attrs.get('exported'),
                 'configChanges': attrs.get('configChanges'),
                 'windowSoftInputMode': attrs.get('windowSoftInputMode')})
        elif tag == 'provider':
            out['providers'].append(
                {'name': attrs.get('name'),
                 'authorities': attrs.get('authorities'),
                 'exported': attrs.get('exported')})
    return out, ax


